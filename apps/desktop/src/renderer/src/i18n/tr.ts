const TABLES: Record<string, Record<string, string>> = { de: DE }

export function tr(en: string): string {
  const lang = (i18n.language || 'en').slice(0, 2)
  const table = TABLES[lang]
  if (!table) return en
  const t = table[en]
  return t === undefined ? en : t
}
